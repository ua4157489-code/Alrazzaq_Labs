# Key Concepts

## if

Executes code when a condition is True.

Example

```python
if age >= 18:
    print("Adult")
```

---

## elif

Checks another condition if previous condition fails.

Example

```python
elif age >= 13:
    print("Teenager")
```

---

## else

Executes when every previous condition is False.

Example

```python
else:
    print("Child")
```

