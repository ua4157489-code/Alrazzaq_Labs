# Cron
# Linux service used for scheduling automated tasks.

# crontab -l
# Lists current scheduled jobs.

# crontab -e
# Opens the user's cron table for editing.

# chmod +x
# Makes a script executable.

# Cron Expression
# Minute Hour Day Month Weekday Command

# Example:
# 0 0 * * * script.sh
# Runs every day at midnight.

# Cron is commonly used for:
# - System backups
# - Log rotation
# - Software updates
# - Monitoring
# - Maintenance tasks
