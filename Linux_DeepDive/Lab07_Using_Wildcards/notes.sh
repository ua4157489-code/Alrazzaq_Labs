echo "

==========================================
Lab 07 Study Notes
Using Wildcards
==========================================

Wildcards

Special characters used
for pattern matching.

------------------------------------------

*

Matches zero or more characters.

Example

cp *.txt backup/

------------------------------------------

?

Matches exactly one character.

Example

rm file?.txt

Matches

file1.txt

file2.txt

------------------------------------------

[]

Matches characters inside brackets.

Example

report[12].txt

Matches

report1.txt

report2.txt

------------------------------------------

Useful Commands

touch

Create files.

cp

Copy files.

rm

Delete files.

ls

List files.

mkdir

Create directory.

==========================================

Learning Outcome

Successfully used
Linux wildcard patterns
to copy,
list,
and remove
multiple files efficiently.

"
