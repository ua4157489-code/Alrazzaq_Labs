# groupadd
# Creates a new Linux group.

# grep /etc/group
# Verifies whether the group exists.

# usermod -aG
# Adds an existing user to a supplementary group.

# groups
# Displays all groups assigned to a user.

# gpasswd -d
# Removes a user from a group.

# Linux groups simplify permission management
# by assigning permissions to multiple users
# through a single group.
