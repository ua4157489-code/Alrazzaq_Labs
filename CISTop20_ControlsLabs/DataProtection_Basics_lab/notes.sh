DATA PROTECTION NOTES
=====================


1. Encryption

Encryption converts readable data into unreadable ciphertext.

Only users with the correct key or password can access the original data.


2. AES-256

AES-256 is a strong symmetric encryption algorithm.

Used for:

- File encryption
- Disk encryption
- Secure storage


3. VeraCrypt

VeraCrypt creates encrypted containers.

Benefits:

- Protects sensitive files
- Provides encrypted storage
- Requires authentication before access


4. HTTPS

HTTPS protects web communication using TLS encryption.

Security improvements:

HTTP:
- No encryption

HTTPS:
- Encrypted communication
- Certificate verification
- Data confidentiality


5. SSH vs Telnet

Telnet:

- Sends data in plaintext
- Vulnerable to interception


SSH:

- Encrypts communication
- Protects credentials
- Secure remote administration


6. SSL/TLS Certificate

Certificates provide:

- Server identity verification
- Encrypted communication
- Secure key exchange


7. Wireshark Validation

Encrypted traffic should show:

- TLS packets
- No readable credentials
- No plaintext sensitive information


8. Security Best Practices

- Use strong passwords
- Encrypt sensitive data
- Disable insecure protocols
- Keep certificates updated
- Monitor encrypted traffic


Lab Result:

Sensitive data was encrypted and secure communication protocols were implemented.


